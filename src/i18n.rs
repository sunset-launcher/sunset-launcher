impl Language {
    pub const ALL: [Language; 9] = [
        Language::En,
        Language::Ru,
        Language::Uk,
        Language::De,
        Language::Fr,
        Language::Es,
        Language::Pl,
        Language::Pt,
        Language::Tr,
    ];

    pub fn label(self) -> &'static str {
        match self {
            Language::En => "English",
            Language::Ru => "Русский",
            Language::Uk => "Українська",
            Language::De => "Deutsch",
            Language::Fr => "Français",
            Language::Es => "Español",
            Language::Pl => "Polski",
            Language::Pt => "Português",
            Language::Tr => "Türkçe",
        }
    }

    pub fn code(self) -> &'static str {
        match self {
            Language::En => "EN",
            Language::Ru => "RU",
            Language::Uk => "UK",
            Language::De => "DE",
            Language::Fr => "FR",
            Language::Es => "ES",
            Language::Pl => "PL",
            Language::Pt => "PT",
            Language::Tr => "TR",
        }
    }
}

